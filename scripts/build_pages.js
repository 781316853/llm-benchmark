function zhUrl(p) {
  return SITE + (p.file === "index.html" ? "" : p.file);
}
function enUrl(p) {
  return SITE + p.en.file.replace(/index\.html$/, "");
}
function pageById(id) {
  return PAGES.filter((p) => p.id === id)[0];
}

// 从模板里按行切成「每个页面一段」:页面 section 顶格缩进 4 空格,内嵌 section 更深,
// 故以 ^    </section> 作为结束边界;上方紧邻的 4 空格注释行属于该段,一并带上。
function splitSections(lines) {
  const sections = [];
  for (let i = 0; i < lines.length; i++) {
    if (!/^    <section class="page(?: active)?" id="page-([a-z0-9]+)">/.test(lines[i])) continue;
    const id = /id="page-([a-z0-9]+)"/.exec(lines[i])[1];
    let start = i;
    while (start > 0 && /^    <!--/.test(lines[start - 1])) start--;
    let end = i;
    while (end < lines.length && !/^    <\/section>/.test(lines[end])) end++;
    if (end >= lines.length) throw new Error("页面 section 未闭合: " + id);
    sections.push({ id: id, start: start, end: end });
    i = end;
  }
  return sections;
}

// 公共 head + 目标页 section + 公共 tail
function assemble(lines, sections, id) {
  const target = sections.filter((s) => s.id === id)[0];
  if (!target) throw new Error("模板中找不到页面: " + id);
  const head = lines.slice(0, sections[0].start).join("\n");
  const tail = lines.slice(sections[sections.length - 1].end + 1).join("\n");
  let body = lines.slice(target.start, target.end + 1).join("\n");
  // 目标页的 section 统一带 active(单页文件里它就是唯一可见页)
  body = body.replace(/^    <section class="page(?: active)?" id="page-([a-z0-9]+)">/m, function (m, pid) {
    return '    <section class="page active" id="page-' + pid + '">';
  });
  return { head: head, body: body, tail: tail };
}

function alternates(p) {
  if (!p.en) return "";
  return '  <link rel="alternate" hreflang="zh-CN" href="' + zhUrl(p) + '" />\n' +
    '  <link rel="alternate" hreflang="en" href="' + enUrl(p) + '" />\n' +
    '  <link rel="alternate" hreflang="x-default" href="' + zhUrl(p) + '" />';
}

// 把模板的公共部分 + 目标页 section 拼成该页 HTML,并改写 head、导航选中态与 body 的 data-page
function buildPage(lines, sections, page) {
  const parts = assemble(lines, sections, page.id);
  let out = parts.head + "\n" + parts.body + "\n" + parts.tail;

  const url = zhUrl(page);
  const subs = [
    [/<title>[\s\S]*?<\/title>/, "<title>" + page.title + "</title>"],
    [/<meta name="description" content="[^"]*" \/>/, '<meta name="description" content="' + page.desc + '" />'],
    [/<link rel="canonical" href="[^"]*" \/>/,
      '<link rel="canonical" href="' + url + '" />' + (alternates(page) ? "\n" + alternates(page) : "")],
    [/<meta property="og:title" content="[^"]*" \/>/, '<meta property="og:title" content="' + page.title + '" />'],
    [/<meta property="og:description" content="[^"]*" \/>/, '<meta property="og:description" content="' + page.desc + '" />'],
    [/<meta property="og:url" content="[^"]*" \/>/, '<meta property="og:url" content="' + url + '" />'],
    [/<meta name="twitter:title" content="[^"]*" \/>/, '<meta name="twitter:title" content="' + page.title + '" />'],
    [/<meta name="twitter:description" content="[^"]*" \/>/, '<meta name="twitter:description" content="' + page.desc + '" />'],
    [/<body data-page="[a-z0-9]*">/, '<body data-page="' + page.id + '">']
  ];
  subs.forEach(function (pair) {
    if (!pair[0].test(out)) throw new Error("模板缺少可替换的标签: " + pair[0] + "(" + page.file + ")");
    out = out.replace(pair[0], pair[1].replace(/\$/g, "$$$$"));
  });

  // 导航选中态:所有 tab 先清空,再给当前页打上 active + aria-current
  out = out.replace(/<a class="tab([^"]*)" data-tab="([a-z0-9]+)" href="([^"]+)"[^>]*>/g,
    function (m, cls, id, href) {
      const on = id === page.id;
      return '<a class="tab' + (on ? " active" : "") + '" data-tab="' + id + '" href="' + href + '"' +
        (on ? ' aria-current="page"' : '') + ">";
    });

  // 生成物标注,避免有人直接改产物
  if (out.indexOf("scripts/build_pages.js") < 0) out = out.replace(/<head>/, "<head>\n" + BANNER);
  return out;
}

function enNav(activeId) {
  const items = PAGES.filter((p) => p.en).map(function (p) {
    const on = p.id === activeId;
    const href = p.en.file.replace(/^en\//, "");
    return '      <a class="tab' + (on ? " active" : "") + '" data-tab="' + p.id + '" href="' + href + '"' +
      (on ? ' aria-current="page"' : '') + ">" + p.en.nav + "</a>";
  });
  return '<div class="tabs-inner">\n' + items.join("\n") + "\n    </div>";
}

function buildPageEn(lines, sections, page) {
  const parts = assemble(lines, sections, page.id);
  let body = parts.body;

  // 英文站不展示中文 AI 热点总结(正文是抓取时中译的),首屏改为单栏基准速览
  if (page.id === "overview") {
    body = body.replace(/^        <!-- AI 热点总结[\s\S]*?^        <\/section>\n/m, "");
    body = body.replace('<div class="overview-top">', '<div class="overview-top no-news">');
    if (body.indexOf("news-section") >= 0) throw new Error("英文总览未能移除新闻区块");
  }

  let out = parts.head + "\n" + body + "\n" + parts.tail;

  // 页面在 /en/ 子目录:样式、脚本、数据、图片改走 ../,按需注入的数据脚本由 body[data-base] 补齐
  out = out.replace(/(\s(?:src|href)=")((?:css|js|data|assets)\/)/g, "$1../$2");
  out = out.replace(/<body data-page="([a-z0-9]+)">/, '<body data-page="$1" data-base="../">');
  // 英文站没有新闻区块,不必加载新闻数据
  out = out.replace(/\n\s*<script defer src="\.\.\/data\/news\.js\?v=[^"]*"><\/script>/, "");

  const url = enUrl(page);
  const subs = [
    [/<html lang="[^"]*">/, '<html lang="en">'],
    [/<body data-page="[a-z0-9]+"/, '<body data-page="' + page.id + '"'],
    [/<title>[\s\S]*?<\/title>/, "<title>" + page.en.title + "</title>"],
    [/<meta name="description" content="[^"]*" \/>/, '<meta name="description" content="' + page.en.desc + '" />'],
    [/<link rel="canonical" href="[^"]*" \/>/,
      '<link rel="canonical" href="' + url + '" />' + (alternates(page) ? "\n" + alternates(page) : "")],
    [/<meta property="og:title" content="[^"]*" \/>/, '<meta property="og:title" content="' + page.en.title + '" />'],
    [/<meta property="og:description" content="[^"]*" \/>/, '<meta property="og:description" content="' + page.en.desc + '" />'],
    [/<meta property="og:url" content="[^"]*" \/>/, '<meta property="og:url" content="' + url + '" />'],
    [/<meta property="og:locale" content="[^"]*" \/>/, '<meta property="og:locale" content="en_US" />'],
    [/<meta property="og:site_name" content="[^"]*" \/>/, '<meta property="og:site_name" content="LLM Coding Benchmark Portal" />'],
    [/<meta name="twitter:title" content="[^"]*" \/>/, '<meta name="twitter:title" content="' + page.en.title + '" />'],
    [/<meta name="twitter:description" content="[^"]*" \/>/, '<meta name="twitter:description" content="' + page.en.desc + '" />']
  ];
  subs.forEach(function (pair) {
    if (!pair[0].test(out)) throw new Error("模板缺少可替换的标签: " + pair[0] + "(" + page.en.file + ")");
    out = out.replace(pair[0], pair[1].replace(/\$/g, "$$$$"));
  });

  // 导航:英文标签,去掉没有英文版的 changelog
  if (!/<div class="tabs-inner">[\s\S]*?<\/div>\n  <\/nav>/.test(out)) {
    throw new Error("模板导航结构与生成器不匹配");
  }
  out = out.replace(/<div class="tabs-inner">[\s\S]*?<\/div>\n  <\/nav>/,
    enNav(page.id) + "\n  </nav>");

  // 语言切换:回到对应的中文页
  const zhHref = "../" + (page.file === "index.html" ? "index.html" : page.file);
  out = out.replace(/<a class="lang-link"[^>]*>[^<]*<\/a>/,
    '<a class="lang-link" href="' + zhHref + '" hreflang="zh-CN" lang="zh-CN" aria-label="切换到中文">中文</a>');

  // 运行时翻译:先字典后引擎(都在 defer 队列末尾,等 app.js 首屏渲染完再遍历 DOM)
  out = out.replace("</head>",
    "  <!-- 英文站运行时翻译:字典 + 引擎;i18n.js 仅在 <html lang=en> 下生效 -->\n" +
    '  <script defer src="../js/i18n-en.js?v=' + EN_VER + '"></script>\n' +
    '  <script defer src="../js/i18n.js?v=' + EN_VER + '"></script>\n</head>');

  if (out.indexOf("scripts/build_pages.js") < 0) out = out.replace(/<head>/, "<head>\n" + BANNER_EN);
  return out;
}

function buildSitemap(lastmod) {
  const urls = [];
  PAGES.forEach(function (p) {
    urls.push({ loc: zhUrl(p), lastmod: lastmod });
    if (p.en) urls.push({ loc: enUrl(p), lastmod: lastmod });
  });
  const body = urls.map(function (u) {
    return "  <url>\n    <loc>" + u.loc + "</loc>\n    <lastmod>" + u.lastmod + "</lastmod>\n  </url>";
  }).join("\n");
  return '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "\n</urlset>\n";
}

function stripLastmod(xml) {
  return xml.replace(/<lastmod>[^<]*<\/lastmod>/g, "<lastmod></lastmod>");
}

function normEol(text) {
  return text.replace(/\r\n/g, "\n");
}

function main() {
  const check = process.argv.indexOf("--check") >= 0;
  const shellText = fs.readFileSync(SHELL, "utf8");
  const lines = shellText.replace(/\r\n/g, "\n").split("\n");
  const sections = splitSections(lines);
  if (sections.length !== PAGES.length) {
    throw new Error("模板页面数(" + sections.length + ")与配置(" + PAGES.length + ")不一致");
  }
  const now = new Date();
  const lastmod = now.getFullYear() + "-" + String(now.getMonth() + 1).padStart(2, "0") + "-" +
    String(now.getDate()).padStart(2, "0");

  const outputs = PAGES.map(function (p) {
    return { file: path.join(ROOT, p.file), text: buildPage(lines, sections, p).replace(/\n/g, "\r\n") };
  });
  const enCount = PAGES.filter((p) => p.en).length;
  PAGES.filter((p) => p.en).forEach(function (p) {
    outputs.push({ file: path.join(ROOT, p.en.file), text: buildPageEn(lines, sections, p).replace(/\n/g, "\r\n") });
  });
  outputs.push({ file: path.join(ROOT, "sitemap.xml"), text: buildSitemap(lastmod).replace(/\n/g, "\r\n") });

  let changed = 0;
  outputs.forEach(function (o) {
    const old = fs.existsSync(o.file) ? fs.readFileSync(o.file, "utf8") : null;
    // 比对时统一换行(CI 在 Linux 上检出的是 LF,生成物是 CRLF);
    // sitemap 的 lastmod 是生成当天日期,也一并不比,否则隔天跑一次就误报
    const same = old !== null && (normEol(old) === normEol(o.text) ||
      (o.file.endsWith("sitemap.xml") &&
        stripLastmod(normEol(old)) === stripLastmod(normEol(o.text))));
    if (same) return;
    changed++;
    if (check) console.log("待更新: " + path.relative(ROOT, o.file));
    else {
      fs.mkdirSync(path.dirname(o.file), { recursive: true });
      fs.writeFileSync(o.file, o.text);
    }
  });

  if (check) {
    if (changed) {
      console.log("产物与模板不一致(" + changed + " 个文件),请执行 npm run pages");
      process.exit(1);
    }
    console.log("页面产物已与模板同步");
    return;
  }
  console.log("已生成 " + PAGES.length + " 个中文页面 + " + enCount + " 个英文页面 + sitemap.xml,变更 " +
    changed + " 个文件");
}

main();
